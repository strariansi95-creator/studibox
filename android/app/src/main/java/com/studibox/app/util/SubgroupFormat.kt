package com.studibox.app.util

/**
 * Подгруппа в данных может прийти по-разному: "1", "1 подгруппа", " 2 ",
 * а для занятий сразу для обеих подгрупп — "1 и 2". Все места UI, где
 * показывается подгруппа, должны идти через эти функции, чтобы никогда не
 * получить "2 подгруппа подгруппа" и не потерять вторую подгруппу из "1 и 2".
 *
 * ВАЖНО: подгруппа — свойство КОНКРЕТНОЙ ПАРЫ, а не преподавателя или
 * студента в целом. Эти функции форматируют значение одного занятия;
 * агрегировать подгруппы нескольких разных занятий в одну подпись
 * (например, "у этого преподавателя вообще есть подгруппы 1 и 2") не нужно —
 * такая агрегация раньше приводила к "Абрамов А.Х. — 1 и 2 подгруппа" в
 * списке преподавателей, хотя подгруппа относится не к нему как к человеку,
 * а к конкретному занятию.
 */
object SubgroupFormat {

    private val digits = Regex("""\d+""")

    /** Короткая метка для компактного чипа-переключателя: "1", "2". */
    fun shortLabel(raw: String): String =
        digits.find(raw)?.value ?: raw.trim()

    /**
     * Полная подпись для текста в карточке одного занятия: "1 подгруппа",
     * либо "1 и 2 подгруппа", если в исходном значении указаны обе
     * подгруппы сразу (занятие проводится для обеих). Слово не дублируется
     * независимо от того, что именно пришло в исходных данных.
     */
    fun fullLabel(raw: String): String {
        val numbers = digits.findAll(raw).map { it.value }.distinct().toList()
        if (numbers.isEmpty()) return raw.trim()
        return "${numbers.joinToString(" и ")} подгруппа"
    }

    /**
     * Показывать ли занятие при выбранной подгруппе [selected]
     * (null/пусто — "Все"). Сравнение идёт по НОМЕРУ подгруппы, а не по
     * сырой строке, поэтому:
     *  - занятие без подгруппы (лекция, практика) видно всем;
     *  - "1 и 2" видно и первой, и второй подгруппе (раньше при выборе
     *    любой из них такое занятие пропадало);
     *  - "2", "2 подгруппа" и " 2 " — одно и то же, независимо от того,
     *    в каком формате подгруппа была сохранена в настройках раньше.
     */
    fun matches(lessonSubgroup: String, selected: String?): Boolean {
        if (selected.isNullOrBlank()) return true
        if (lessonSubgroup.isBlank()) return true
        val wanted = shortLabel(selected)
        val numbers = digits.findAll(lessonSubgroup).map { it.value }.toList()
        return if (numbers.isEmpty()) lessonSubgroup.trim() == selected.trim() else wanted in numbers
    }
}
