-- Studibox: схема расписания.
-- Скрипт идемпотентный и аддитивный: существующие данные не удаляются.

create table if not exists public.groups (
    id          bigint generated by default as identity primary key,
    name        text not null unique,
    created_at  timestamptz not null default now()
);

create table if not exists public.schedule (
    id           bigint generated by default as identity primary key,
    group_id     bigint not null references public.groups(id) on delete cascade,
    group_name   text   not null,
    date         date   not null,
    -- 1 = понедельник ... 7 = воскресенье. Всегда вычисляется из date.
    day_of_week  smallint not null check (day_of_week between 1 and 7),
    lesson_number smallint not null default 0,
    start_time   text not null default '',
    end_time     text not null default '',
    subject      text not null default '',
    teacher      text not null default '',
    classroom    text not null default '',
    week_type    text not null default '',
    subgroup     text not null default '',
    version      integer not null default 0,
    created_at   timestamptz not null default now(),
    -- защита от дублирования занятий
    unique (group_name, date, lesson_number, subgroup, subject)
);

create index if not exists schedule_group_date_idx on public.schedule (group_name, date);
create index if not exists schedule_group_dow_idx  on public.schedule (group_name, day_of_week);

create table if not exists public.metadata (
    key        text primary key,
    value      text,
    updated_at timestamptz not null default now()
);

-- Журнал импортов: помогает понять, почему расписание не обновилось.
create table if not exists public.import_log (
    id          bigint generated by default as identity primary key,
    started_at  timestamptz not null default now(),
    status      text not null,
    message     text,
    sha256      text,
    lessons     integer,
    groups      integer
);

-- Триггер: day_of_week всегда пересчитывается из даты,
-- даже если импортёр прислал значение из текста XLSX.
create or replace function public.enforce_day_of_week()
returns trigger
language plpgsql
as $$
begin
    -- ISO: extract(isodow) даёт 1=понедельник ... 7=воскресенье
    new.day_of_week := extract(isodow from new.date)::smallint;
    return new;
end;
$$;

drop trigger if exists schedule_day_of_week_trg on public.schedule;
create trigger schedule_day_of_week_trg
    before insert or update on public.schedule
    for each row execute function public.enforce_day_of_week();
